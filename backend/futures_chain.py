def _detect_turning_points(path, max_phases=8):
    """在价格路径上找局部极大/极小值，贪心保留最能解释价格波动的拐点，
    返回用于切分阶段的索引边界列表（含端点）。目标段数 = max_phases。"""
    dates = [d for d, _ in path]; closes = [c for _, c in path]
    n = len(dates)
    if n < 5:
        return [0, n - 1] if n > 1 else [0]
    cand = []
    for i in range(1, n - 1):
        if closes[i] >= closes[i - 1] and closes[i] >= closes[i + 1]:
            cand.append(i)
        elif closes[i] <= closes[i - 1] and closes[i] <= closes[i + 1]:
            cand.append(i)
    cand = sorted(set([0] + cand + [n - 1]))
    if len(cand) <= max_phases + 1:
        return cand

    def _score(bounds):
        s = 0.0
        for a, b in zip(bounds, bounds[1:]):
            s += abs(closes[b] - closes[a])
        return s

    internal = cand[1:-1]
    bounds = [0, n - 1]
    while len(bounds) < max_phases + 1:
        best = None; bestscore = -1
        for c in internal:
            if c in bounds:
                continue
            sc = _score(sorted(bounds + [c]))
            if sc > bestscore:
                bestscore = sc; best = c
        if best is None:
            break
        bounds = sorted(bounds + [best])
    return bounds


def _build_phases(path, tret, others, max_phases=8):
    """切分涨/跌阶段，每段给出涨跌幅与区间内 Top 联动品种。"""
    dates = [d for d, _ in path]; closes = [c for _, c in path]
    n = len(dates)
    if n < 5:
        return []
    bounds = _detect_turning_points(path, max_phases=max_phases)
    phases = []
    for s in range(len(bounds) - 1):
        i0, i1 = bounds[s], bounds[s + 1]
        if i1 <= i0:
            continue
        d0, d1 = dates[i0], dates[i1]
        c0, c1 = closes[i0], closes[i1]
        pct = (c1 - c0) / c0 * 100 if c0 else 0.0
        direction = "涨" if pct >= 0 else "跌"
        seg_t = tret[i0:i1]
        movers = []
        for key, arr in others.items():
            seg_o = arr[i0:i1]
            r, _ = _pearson(seg_t, seg_o)
            if abs(r) > 0.04:
                movers.append((key, r))
        movers.sort(key=lambda x: abs(x[1]), reverse=True)
        top = [{"exchange": k[0], "symbol": k[1],
                "name": NAME_MAP.get(k[1].upper(), k[1].upper()),
                "raw": round(float(r), 3)} for k, r in movers[:3]]
        phases.append({"start": d0, "end": d1, "direction": direction,
                       "pct": round(pct, 1), "top": top})
    return phases


def _detect_shocks(target_series, others, topn=8, gap=5):
    """从真实行情中检测显著异动日（单日涨跌幅最大的若干天）。

    与 _build_phases 的区别：phases 看"阶段区间涨跌幅"，shocks 看"单日冲击"。
    每天给出：日期 / 单日涨跌幅 / 当日联动最强的其他品种（同日收益，作为"传导证据"）。
    这是纯数据驱动的真实事件，任何有行情数据的品种都能产出（不依赖外部新闻源）。
    """
    dates = sorted(target_series.keys())
    if len(dates) < 30:
        return []
    moves = []
    for i in range(1, len(dates)):
        p0 = target_series[dates[i - 1]]
        p1 = target_series[dates[i]]
        if not p0:
            continue
        moves.append((dates[i], (p1 - p0) / p0 * 100, i))
    if not moves:
        return []
    # 按绝对值取最大，但相邻 gap 个交易日内只保留一个（避免同一波行情重复计数）
    moves.sort(key=lambda x: abs(x[1]), reverse=True)
    picked, used = [], []
    for d, pct, i in moves:
        if any(abs(i - j) < gap for j in used):
            continue
        used.append(i)
        picked.append((d, pct, i))
        if len(picked) >= topn:
            break
    picked.sort(key=lambda x: x[0])  # 输出按日期升序
    out = []
    for d, pct, i in picked:
        comovers = []
        for key, arr in others.items():
            # others 数组按收益日期对齐：索引 i-1 对应 dates[i] 的日收益
            if i - 1 < len(arr):
                v = arr[i - 1]
                if v is not None and not np.isnan(v):
                    comovers.append((key, float(v)))
        comovers.sort(key=lambda x: abs(x[1]), reverse=True)
        out.append({
            "date": d,
            "pct": round(float(pct), 2),
            "direction": "涨" if pct >= 0 else "跌",
            "top": [{"exchange": k[0], "symbol": k[1],
                     "name": NAME_MAP.get(k[1].upper(), k[1].upper()),
                     "ret": round(v * 100, 2)} for k, v in comovers[:3]],
        })
    return out


def _sector_link(tarr, others, mkt):
    """板块联动强度：把同板块多个品种等权合成「板块指数」，再与本品种算相关。

    返回各板块的平均 原始/偏 相关（按 |r| 降序）。用于判断本品种的联动主要来自
    「板块内共振」还是「跨板块传导」。纯数据驱动，所有品种可用。
    """
    sec_members = {}
    for key, arr in others.items():
        sec = SECTOR.get(key[1].upper(), "其他")
        sec_members.setdefault(sec, []).append(arr)
    out = []
    for sec, arrs in sec_members.items():
        if not arrs:
            continue
        stack = np.vstack(arrs)
        # 仅对"至少有一个品种有数据"的交易日求板块均值，避免整列全 NaN 触发 nanmean 警告
        col_valid = ~np.isnan(stack).all(axis=0)
        avg = np.full(stack.shape[1], np.nan)
        if col_valid.any():
            avg[col_valid] = np.nanmean(stack[:, col_valid], axis=0)
        mask = ~(np.isnan(avg) | np.isnan(tarr))
        if mask.sum() < 30 or np.std(avg[mask]) == 0:
            continue
        r_raw, _ = _pearson(tarr[mask], avg[mask])
        r_part = _partial(tarr[mask], avg[mask], mkt[mask])
        out.append({"sector": sec, "raw": round(float(r_raw), 3),
                    "partial": round(float(r_part), 3), "n": int(mask.sum()),
                    "members": len(arrs)})
    out.sort(key=lambda x: abs(x["raw"]), reverse=True)
    return out


def _sector_matrix(varieties, from_date=None, to_date=None):
    """板块共振全景矩阵：对一组品种各取 _sector_link，拼成 品种 × 板块 的共振强度矩阵。

    参数 varieties: [(symbol, exchange), ...]
        from_date/to_date: 可选时间区间（YYYY-MM-DD），透传给 analyze，用于看特定窗口的板块共振结构。
    返回 {"ok":True, "rows":[{symbol,exchange,name,sector,vol,beta,cells:{sector:{raw,partial}}}],
          "sectors":[...按名称稳定排序...]}
    cells 的 raw = 本品种与该板块平均(原始)相关；partial = 剔除等权市场因子后的偏相关。
    每行的 sector = 该品种自身所属板块；前端据此把「列板块 == 行板块」的单元格标为
    「板块内共振」（组内同步性），其余标为「跨板块传导」（溢出效应）。
    用于从组合视角一眼看全"谁在跟哪个板块共振"。纯数据驱动，离线可用。
    """
    rows = []
    sec_order = []
    seen = set()
    for sym, ex in varieties:
        try:
            d = analyze(sym, ex, from_date=from_date, to_date=to_date)
        except Exception:
            continue
        if not d.get("ok"):
            continue
        secs = d.get("sectors") or []
        cells = {}
        for s in secs:
            cells[s["sector"]] = {"raw": round(float(s["raw"]), 3),
                                  "partial": round(float(s["partial"]), 3)}
            if s["sector"] not in seen:
                seen.add(s["sector"]); sec_order.append(s["sector"])
        rows.append({
            "symbol": sym.upper(), "exchange": ex,
            "name": d.get("name", sym.upper()),
            # 品种自身板块：前端用它区分「板块内共振」与「跨板块传导」
            "sector": SECTOR.get(sym.upper(), "其他"),
            "vol": d.get("vol"), "beta": d.get("beta"),
            "cells": cells,
        })
    sec_order.sort()
    return {"ok": True, "rows": rows, "sectors": sec_order}


# ---------------------------------------------------------------------------
# 主分析
# ---------------------------------------------------------------------------
def analyze(symbol, exchange, topn=12, from_date=None, to_date=None):
    """分析给定品种的产业链联动。

    参数:
      symbol, exchange: 必填
      topn: 相关性 Top N 数量，默认 12
      from_date / to_date: 可选区间过滤（字符串 "YYYY-MM-DD"）；None 或空串视为不限
    """
    symbol = (symbol or "").strip()
    exchange = (exchange or "SHFE").strip().upper()
    from_date = (from_date or "").strip() or None
    to_date = (to_date or "").strip() or None

    def _in(d):
            if from_date and d < from_date: return False
            if to_date and d > to_date: return False
            return True

    allseries = _load_all()
    tkey = None
    for (ex, sym) in allseries:
        if sym.upper() == symbol.upper() and ex == exchange:
            tkey = (ex, sym)
            break
    if tkey is None:
        return {"ok": False, "error": "未找到该品种缓存：%s.%s（后端 data/ 下无对应 futures_%s_%s.json）"
                % (exchange, symbol, exchange, symbol)}

    # 应用日期区间（target）
    full_t = allseries[tkey]
    target_series = {d: v for d, v in full_t.items() if _in(d)} if (from_date or to_date) else full_t
    if len(target_series) < 30:
        return {"ok": False, "error": "区间 [{} ~ {}] 内样本不足 30 天（仅 {} 天）".format(
            from_date or "起始", to_date or "至今", len(target_series))}

    tdates, tret = _returns(target_series)

    # 其它品种：同样按区间过滤后与 target 对齐
    others = {}
    for key, s in allseries.items():
        if key == tkey:
            continue
        if from_date or to_date:
            s = {d: v for d, v in s.items() if _in(d)}
        if not s:
            continue
        d, r = _returns(s)
        rm = {dd: vv for dd, vv in zip(d, r)}
        others[key] = np.array([rm.get(dd, np.nan) for dd in tdates], dtype=float)

    tarr = np.array(tret, dtype=float)
    if others:
        M = np.vstack(list(others.values()))
        # 逐列求均值，跳过整列全 NaN（避免出现 "Mean of empty slice" 警告）
        mkt = np.zeros(M.shape[1], dtype=float)
        for _c in range(M.shape[1]):
            col = M[:, _c]
            if np.any(~np.isnan(col)):
                mkt[_c] = np.nanmean(col)
    else:
        mkt = np.zeros_like(tarr)

    results = []
    for key, arr in others.items():
        mask = ~(np.isnan(arr) | np.isnan(tarr))
        if mask.sum() < 30:
            continue
        r_raw, n = _pearson(tarr[mask], arr[mask])
        r_part = _partial(tarr[mask], arr[mask], mkt[mask])
        results.append({
            "exchange": key[0], "symbol": key[1],
            "name": NAME_MAP.get(key[1].upper(), key[1].upper()),
            "sector": SECTOR.get(key[1].upper(), "其他"),
            "raw": round(float(r_raw), 3),
            "partial": round(float(r_part), 3),
            "n": int(mask.sum()),
        })
    results.sort(key=lambda x: abs(x["raw"]), reverse=True)

    # 年化波动率 + 市场β（相对等权市场因子 mkt）
    _tv = tarr[~np.isnan(tarr)]
    vol = float(np.std(_tv)) * np.sqrt(242) * 100 if _tv.size >= 2 else 0.0
    beta = 0.0
    if others:
        _mm = ~(np.isnan(tarr) | np.isnan(mkt))
        if _mm.sum() >= 30 and np.std(mkt[_mm]) > 0:
            beta = float(np.cov(tarr[_mm], mkt[_mm])[0, 1] / np.var(mkt[_mm]))

    # 阶段 / 拐点时间轴（区间感知）：用区间内 target 路径切分涨/跌阶段
    path = [[d, round(target_series[d], 1)] for d in sorted(target_series.keys())]
    max_phases = max(4, min(10, len(path) // 30))
    phases = _build_phases(path, tret, others, max_phases=max_phases)

    # 真实异动事件（数据驱动）：单日冲击最大的若干天 + 当日联动最强的品种
    shocks = _detect_shocks(target_series, others, topn=8)

    # 板块联动强度（数据驱动）：本品种 vs 各板块平均相关
    sectors = _sector_link(tarr, others, mkt)

    # 价格路径统计（用区间内 target）
    s = target_series
    dates = sorted(s.keys())
    closes = [s[d] for d in dates]
    ytd = (closes[-1] - closes[0]) / closes[0] * 100
    hi = max(closes); lo = min(closes)
    hi_d = dates[closes.index(hi)]; lo_d = dates[closes.index(lo)]

    return {
        "ok": True,
        "symbol": symbol.upper(), "exchange": exchange,
        "name": NAME_MAP.get(symbol.upper(), symbol.upper()),
        "target_path": [[d, round(s[d], 1)] for d in dates],
        "ytd": round(ytd, 1),
        "high": [hi_d, round(hi, 0)],
        "low": [lo_d, round(lo, 0)],
        "corr": results[:topn],
        "n_varieties": len(allseries),
        "vol": round(vol, 1),
        "beta": round(beta, 2),
        "chain": CHAIN_KB.get(symbol.upper()),
        "offline": OFFLINE_MODE,
        "start": dates[0], "end": dates[-1],
        "from_date": from_date, "to_date": to_date,
        "phases": phases,
        "shocks": shocks,
        "sectors": sectors,
    }


