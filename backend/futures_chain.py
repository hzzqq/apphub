def _load_series(exchange, symbol):
    """读单个品种缓存（大小写不敏感），返回 {date: close}。"""
    for sym in (symbol, symbol.upper(), symbol.lower()):
        p = os.path.join(DATA_DIR, "futures_%s_%s.json" % (exchange, sym))
        if os.path.exists(p):
            try:
                with open(p, encoding="utf-8") as f:
                    arr = json.load(f)
                if isinstance(arr, list) and arr:
                    return {r["date"]: float(r["close"]) for r in arr if r.get("close") is not None}
            except Exception:
                pass
    return None


def _load_all():
    """加载全部期货缓存，返回 {(exchange, symbol): {date: close}}。"""
    out = {}
    for fp in sorted(glob.glob(os.path.join(DATA_DIR, "futures_*.json"))):
        base = os.path.basename(fp)
        m = re.match(r"futures_(SHFE|DCE|CZCE|INE)_(.+)\.json", base)
        if not m:
            continue
        ex, sym = m.group(1), m.group(2)
        try:
            with open(fp, encoding="utf-8") as f:
                arr = json.load(f)
            s = {r["date"]: float(r["close"]) for r in arr if r.get("close") is not None}
            if s:
                out[(ex, sym)] = s
        except Exception:
            pass
    return out


def _returns(series):
    """返回 (dates[1:], 日对数收益 ndarray)。"""
    dates = sorted(series.keys())
    vals = np.array([series[d] for d in dates], dtype=float)
    ret = np.diff(np.log(vals))
    return dates[1:], ret


def _pearson(a, b):
    a = np.asarray(a, float); b = np.asarray(b, float)
    m = ~(np.isnan(a) | np.isnan(b))
    a, b = a[m], b[m]
    if len(a) < 30 or np.std(a) == 0 or np.std(b) == 0:
        return 0.0, len(a)
    r = np.corrcoef(a, b)[0, 1]
    return float(r) if np.isfinite(r) else 0.0, len(a)


def _partial(a, b, mkt):
    """剔除市场因子后的偏相关：分别对市场回归取残差再相关。"""
    def resid2(x, mk):
        x = np.asarray(x, float); mk = np.asarray(mk, float)
        mm = ~(np.isnan(x) | np.isnan(mk))
        x, mk = x[mm], mk[mm]
        if len(x) < 5 or np.std(mk) == 0:
            return np.zeros_like(x)
        A = np.vstack([mk, np.ones_like(mk)]).T
        coef, _, _, _ = np.linalg.lstsq(A, x, rcond=None)
        return x - (coef[0] * mk + coef[1])
    ra = resid2(a, mkt); rb = resid2(b, mkt)
    r, _ = _pearson(ra, rb)
    return r


